/** What every host backend implements, plus the JS-facing pieces both hosts share. */
import type { IRFunction, IRModule, IRStruct, NativeType } from "@lucent/compiler";

/** Relative path → file contents. */
export type FileTree = Map<string, string>;

export interface EmitOptions {
  /** Name of the generated native package/module folder (e.g. `lucent`). */
  packageName: string;
}

export interface Host {
  readonly name: "expo" | "nitro";
  /** All Lucent modules of an app become one native package. */
  emitPackage(modules: IRModule[], options: EmitOptions): FileTree;
  /** The JavaScript module that replaces `<name>.lucent.ts` in the bundle, plus its declarations. */
  emitProxy(module: IRModule): { js: string; dts: string };
  /** Runs after the tree is written (Nitro runs `nitrogen` here). */
  postGenerate?(packageDir: string): Promise<void>;
}

export const GENERATED_HEADER = "// Generated by Lucent. Do not edit.\n";

const JS_PRIMITIVES: Readonly<Record<string, string>> = {
  void: "void",
  bool: "boolean",
  string: "string",
  bytes: "Uint8Array",
};

export function jsType(t: NativeType): string {
  switch (t.kind) {
    case "float":
    case "int":
      return "number";
    case "array": {
      const element = jsType(t.element);
      return t.element.kind === "optional" ? `(${element})[]` : `${element}[]`;
    }
    case "map":
      return `Record<string, ${jsType(t.value)}>`;
    case "optional":
      return `${jsType(t.value)} | null`;
    case "struct":
      return t.name;
    case "promise":
      return `Promise<${jsType(t.value)}>`;
    default:
      return JS_PRIMITIVES[t.kind]!;
  }
}

export function functionSignature(fn: IRFunction): string {
  const params = fn.params.map((p) => `${p.name}: ${jsType(p.type)}`).join(", ");
  const ret = fn.async ? `Promise<${jsType(fn.returnType)}>` : jsType(fn.returnType);
  return `${fn.name}(${params}): ${ret}`;
}

export function structDeclaration(s: IRStruct): string {
  return `export type ${s.name} = {\n${s.fields.map((f) => `  ${f.name}: ${jsType(f.type)};`).join("\n")}\n};`;
}

/** `.d.ts` contents for a module: exported structs and exported functions. */
export function declarations(module: IRModule): string {
  const structs = module.structs.filter((s) => s.exported).map(structDeclaration);
  const functions = module.functions
    .filter((f) => f.exported)
    .map((f) => `export declare function ${functionSignature(f)};`);
  return [...structs, ...(structs.length && functions.length ? [""] : []), ...functions].join("\n") + "\n";
}

/** `async-sum` → `AsyncSum`: a safe identifier for class and file names. */
export function moduleIdentifier(name: string): string {
  return name
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

export const exportedFunctions = (module: IRModule): IRFunction[] => module.functions.filter((f) => f.exported);

/** True when values of this type need a JS-side conversion at the boundary (bytes ↔ ArrayBuffer). */
export function needsConversion(
  t: NativeType,
  structs: ReadonlyMap<string, IRStruct>,
  seen = new Set<string>(),
): boolean {
  switch (t.kind) {
    case "bytes":
      return true;
    case "array":
    case "optional":
    case "promise":
      return needsConversion(t.kind === "array" ? t.element : t.value, structs, seen);
    case "map":
      return needsConversion(t.value, structs, seen);
    case "struct": {
      if (seen.has(t.name)) return false;
      seen.add(t.name);
      return structs.get(t.name)?.fields.some((f) => needsConversion(f.type, structs, seen)) ?? false;
    }
    default:
      return false;
  }
}

/**
 * A JS expression converting `value` of type `t` across the boundary.
 * `direction` "in" turns app values into host values (Uint8Array → ArrayBuffer); "out" is the reverse.
 */
export function convert(
  value: string,
  t: NativeType,
  direction: "in" | "out",
  structs: ReadonlyMap<string, IRStruct>,
): string {
  if (!needsConversion(t, structs)) return value;
  switch (t.kind) {
    case "bytes":
      return direction === "in" ? `toArrayBuffer(${value})` : `fromArrayBuffer(${value})`;
    case "array":
      return `${value}.map((x) => ${convert("x", t.element, direction, structs)})`;
    case "optional":
      return `(${value} == null ? null : ${convert(value, t.value, direction, structs)})`;
    case "promise":
      return `${value}.then((x) => ${convert("x", t.value, direction, structs)})`;
    case "map":
      return `Object.fromEntries(Object.entries(${value}).map(([k, x]) => [k, ${convert("x", t.value, direction, structs)}]))`;
    case "struct": {
      const fields = structs
        .get(t.name)!
        .fields.filter((f) => needsConversion(f.type, structs))
        .map((f) => `${f.name}: ${convert(`${value}.${f.name}`, f.type, direction, structs)}`);
      return `{ ...${value}, ${fields.join(", ")} }`;
    }
    default:
      return value;
  }
}

/** The exported-function wrappers shared by both hosts' proxies; `call` renders the native invocation. */
export function proxyFunctions(module: IRModule, call: (fn: IRFunction, args: string[]) => string): string {
  const structs = new Map(module.structs.map((s) => [s.name, s]));
  return exportedFunctions(module)
    .map((fn) => {
      const params = fn.params.map((p) => p.name);
      const args = fn.params.map((p) => convert(p.name, p.type, "in", structs));
      const resultType: NativeType = fn.async ? { kind: "promise", value: fn.returnType } : fn.returnType;
      const invocation = `lucentCall(() => ${call(fn, args)})`;
      return `export function ${fn.name}(${params.join(", ")}) {\n  return ${convert(invocation, resultType, "out", structs)};\n}`;
    })
    .join("\n\n");
}

/** Imports only the runtime helpers a proxy body actually uses. */
export function runtimeImport(body: string): string {
  const names = ["lucentCall", "toArrayBuffer", "fromArrayBuffer"].filter((n) => body.includes(`${n}(`));
  return `import { ${names.join(", ")} } from "@lucent/runtime";`;
}
