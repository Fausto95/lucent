import { describe, expect, it } from "vite-plus/test";
import { xml } from "../src/index.ts";

describe("XML documents", () => {
  it("print a declaration, a comment and nested elements, attributes escaped", () => {
    const text = xml.printDocument({
      comment: "Generated by Lucent. Do not edit.",
      root: xml.element(
        "manifest",
        { "xmlns:android": "http://schemas.android.com/apk/res/android" },
        [
          xml.element("uses-permission", { "android:name": "android.permission.CAMERA" }),
          xml.element("meta-data", { "android:value": 'a "b" & <c>' }),
        ],
      ),
    });
    expect(text).toBe(
      [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by Lucent. Do not edit. -->",
        '<manifest xmlns:android="http://schemas.android.com/apk/res/android">',
        '  <uses-permission android:name="android.permission.CAMERA" />',
        '  <meta-data android:value="a &quot;b&quot; &amp; &lt;c&gt;" />',
        "</manifest>",
        "",
      ].join("\n"),
    );
  });

  it("print an element without children open and closed on one line each", () => {
    const text = xml.printDocument({ root: xml.element("manifest", {}, []) });
    expect(text).toBe(
      ['<?xml version="1.0" encoding="utf-8"?>', "<manifest>", "</manifest>", ""].join("\n"),
    );
  });
});
