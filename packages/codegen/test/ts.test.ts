describe("TypeScript type parameters", () => {
  it("print their constraints on functions, methods and call signatures", () => {
    const scalar = union([ts.keyword("boolean"), num, str]);
    const V = { name: "V", extends: scalar };
    const text = ts.printUnit({
      decls: [
        {
          k: "interface",
          name: "$Picker",
          local: true,
          members: [
            {
              k: "call",
              typeParams: [V],
              params: [ts.param("selection", ref("Bound", ref("V")))],
              ret: ref("Picker"),
            },
          ],
        },
        {
          k: "interface",
          name: "View",
          members: [
            {
              k: "method",
              name: "onChange",
              typeParams: [V],
              params: [
                ts.param("of", ref("V")),
                ts.param("action", ts.fn([ts.param("arg0", ref("V"))], ts.keyword("void"))),
              ],
              ret: ref("View"),
            },
          ],
        },
        {
          k: "function",
          name: "same",
          typeParams: [{ name: "T", extends: num, default: ts.literal(0) }],
          params: [ts.param("value", ref("T"))],
          ret: ref("T"),
        },
        { k: "exportNothing" },
      ],
    });

    expect(text).toContain("  <V extends boolean | number | string>(selection: Bound<V>): Picker;");
    expect(text).toContain(
      "  onChange<V extends boolean | number | string>(of: V, action: (arg0: V) => void): View;",
    );
    expect(text).toContain("export declare function same<T extends number = 0>(value: T): T;");
  });
});
