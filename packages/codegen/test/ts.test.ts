import { describe, expect, it } from "vite-plus/test";
import { ts } from "../src/index.ts";

const { ref, union, printType } = ts;
const num = ts.keyword("number");
const str = ts.keyword("string");
const A = ref("A");

describe("TypeScript types", () => {
  it("parenthesize array elements and union members by precedence only", () => {
    expect(printType(ts.array(union([A, ts.nullType])))).toBe("(A | null)[]");
    expect(printType(ts.array(ref("Record", str, num)))).toBe("Record<string, number>[]");
    expect(printType(ts.array(ts.fn([ts.param("arg0", num)], ts.keyword("void"))))).toBe(
      "((arg0: number) => void)[]",
    );
    expect(printType(union([ref("Runnable"), ts.fn([ts.param("arg0", num)], num)]))).toBe(
      "Runnable | ((arg0: number) => number)",
    );
  });

  it("flatten unions and keep one of each member", () => {
    expect(printType(union([union([A, ts.nullType]), ts.nullType]))).toBe("A | null");
    expect(printType(union([A]))).toBe("A");
  });

  it("print object, literal and typeof types", () => {
    expect(printType(ts.object([{ name: "prototype", type: A, readonly: true }]))).toBe(
      "{ readonly prototype: A }",
    );
    expect(printType(ts.object([]))).toBe("{}");
    expect(
      printType(ts.object([{ name: "__brand", type: ts.keyword("never"), optional: true }])),
    ).toBe("{ __brand?: never }");
    expect(printType(ts.literal('a"b'))).toBe('"a\\"b"');
    expect(printType(ts.literal(-1))).toBe("-1");
    expect(printType(ts.typeOf("Toast.LENGTH_SHORT"))).toBe("typeof Toast.LENGTH_SHORT");
  });

  it("print tuples, their optional elements parenthesized by precedence", () => {
    expect(printType(ts.tuple([{ type: A }, { type: num, optional: true }]))).toBe("[A, number?]");
    expect(printType(ts.tuple([{ type: union([A, ts.nullType]), optional: true }]))).toBe(
      "[(A | null)?]",
    );
    expect(printType(ts.array(ts.tuple([{ type: A }])))).toBe("[A][]");
  });

  it("print optional properties", () => {
    expect(
      ts.printUnit({
        decls: [
          {
            k: "interface",
            name: "Attributes",
            members: [{ k: "property", name: "padding", type: num, optional: true }],
          },
        ],
      }),
    ).toBe("export declare interface Attributes {\n  padding?: number;\n}\n");
  });

  it("print a property taking more when written as a get and a set accessor", () => {
    const listener = union([A, ts.nullType]);

    expect(
      ts.printUnit({
        decls: [
          {
            k: "class",
            name: "Dial",
            members: [
              {
                k: "property",
                name: "listener",
                type: listener,
                set: union([A, ts.fn([ts.param("arg0", num)], ts.keyword("void")), ts.nullType]),
                doc: "Its listener.",
              },
            ],
          },
        ],
      }),
    ).toBe(
      "export declare class Dial {\n  /** Its listener. */\n  get listener(): A | null;\n  set listener(value: A | ((arg0: number) => void) | null);\n}\n",
    );
  });

  it("print intersections, parenthesized by precedence", () => {
    expect(printType(ts.intersection([ts.object([{ name: "a", type: A }]), ref("B")]))).toBe(
      "{ a: A } & B",
    );
    expect(printType(ts.intersection([union([A, ts.nullType]), ref("B")]))).toBe("(A | null) & B");
    expect(printType(union([ts.intersection([A, ref("B")]), ts.nullType]))).toBe("A & B | null");
    expect(printType(ts.array(ts.intersection([A, ref("B")])))).toBe("(A & B)[]");
    expect(printType(ts.intersection([A]))).toBe("A");
  });

  it("print bigints and their literals", () => {
    expect(printType(ts.keyword("bigint"))).toBe("bigint");
    expect(printType(ts.literal(9223372036854775807n))).toBe("9223372036854775807n");
    expect(printType(ts.literal(-1n))).toBe("-1n");
  });
});

