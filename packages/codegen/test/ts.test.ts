describe("JavaScript statements", () => {
  it("print a module proxy's CommonJS", () => {
    const m = ts.name("m");
    const text = ts.printUnit({
      decls: [
        ts.stmt(ts.exprStmt(ts.str("use strict"))),
        ts.stmt({
          k: "const",
          name: ["loadModule", "lucentClass"],
          init: ts.call(ts.name("require"), [ts.str("./runtime.js")]),
        }),
        ts.stmt({
          k: "const",
          name: "m",
          init: ts.call(ts.name("loadModule"), [
            ts.str("main"),
            ts.arrow([], ts.member(ts.call(ts.name("require"), [ts.str("react-native")]), "X")),
          ]),
        }),
        ts.stmt(ts.exprStmt(ts.assign(ts.member(ts.name("exports"), "f"), ts.member(m, "f")))),
        ts.stmt(
          ts.exprStmt(
            ts.call(ts.member(ts.name("Object"), "freeze"), [
              ts.objectLit([
                { key: "A", value: ts.num(1), quoted: true },
                { key: "value", value: ts.bool(true) },
              ]),
            ]),
          ),
        ),
      ],
    });
    expect(text).toBe(
      [
        '"use strict";',
        'const { loadModule, lucentClass } = require("./runtime.js");',
        'const m = loadModule("main", () => require("react-native").X);',
        "exports.f = m.f;",
        'Object.freeze({ "A": 1, value: true });',
        "",
      ].join("\n"),
    );
  });

  it("print arrays, null, and literals one entry per line when asked", () => {
    const config = ts.objectLit(
      [
        { key: "name", value: ts.str("LucentMeter_0") },
        { key: "props", value: ts.arrayLit([ts.num(0), ts.nullLit], true) },
        { key: "empty", value: ts.arrayLit([], true) },
        { key: "inline", value: ts.arrayLit([ts.objectLit([{ key: "n", value: ts.num(0) }])]) },
      ],
      true,
    );
    const text = ts.printUnit({ decls: [ts.stmt({ k: "const", name: "config", init: config })] });

    expect(text).toBe(
      [
        "const config = {",
        '  name: "LucentMeter_0",',
        "  props: [",
        "    0,",
        "    null,",
        "  ],",
        "  empty: [],",
        "  inline: [{ n: 0 }],",
        "};",
        "",
      ].join("\n"),
    );
  });
});

