/**
 * A helper view as a Kotlin composable (ui/view-helpers.ts): its values,
 * which the setup computes where it is used, its callbacks, what its user
 * gives it, and its code: its composition statements, then its content.
 */
interface HelperFunction {
  readonly helper: ViewHelper;
  readonly name: string;
  readonly values: readonly HelperValue[];
  readonly body: kt.Stmt[];
}

/**
 * A value of a helper view: `source`, in its code or in a helper it uses
 * (`via`: those uses, innermost first, the last in this helper's code).
 */
interface HelperValue {
  readonly name: string;
  readonly source: ts.Expression;
  readonly type: ViewType;
  readonly via?: HelperUse;
}

/** The helper view a writer writes, and the values it has met so far. */
interface Frame {
  readonly helper: ViewHelper;
  readonly values: HelperValue[];
}

/** What the writers of one body share: the component's name, and its helper views. */
interface Shared {
  readonly registration: string;
  readonly helpers: Map<FunctionLike, HelperFunction>;
}

/** A helper view's composable: a parameter per value and per callback. */
function helperFun(values: KotlinValues, h: HelperFunction): kt.Decl {
  return {
    k: "fun",
    annotations: ["Composable"],
    modifiers: [],
    name: h.name,
    params: [
      ...h.values.map((v) => kt.param(v.name, values.type(v.type))),
      ...h.helper.callbacks.map((c) =>
        kt.param(
          c.name,
          kt.fn(
            c.params.map((k) => kt.type(KOTLIN_TYPES[k])),
            kt.type("Unit"),
          ),
        ),
      ),
    ],
    body: h.body,
  };
}

const KOTLIN_TYPES: Record<ScalarType["k"], string> = {
  number: "Double",
  boolean: "Boolean",
  string: "String",
};

function kotlinType(t: ScalarType): kt.Type {
  const named = kt.type(KOTLIN_TYPES[t.k]);

  return t.nullable ? kt.nullable(named) : named;
}

function actionType(a: ActionSlot): kt.Type {
  return kt.fn(
    a.params.map((p) => kotlinType(crossingOf(p))),
    kt.type("Unit"),
  );
}

/** A field's type: an optional one may be missing, which Kotlin holds as null. */
function fieldType(f: ViewField): ViewType {
  return f.optional && f.type.k !== "nullable" ? { k: "nullable", inner: f.type } : f.type;
}

/**
 * The Kotlin side of plain data (emit/toolkit-values.ts): each value's
 * Kotlin type, its first value, and how it is read from the boxed Java
 * objects that encode it. An object is a data class of its own (equal
 * values keep Compose state unchanged), read from a record by a function
 * of the file.
 */
class KotlinValues {
  /** The data classes of the objects met, and their readers. */
  readonly decls: kt.Decl[] = [];

  private readonly names = new Map<string, string>();
  private readonly prefix: string;

  constructor(prefix: string) {
    this.prefix = prefix;
  }

  type(t: ViewType): kt.Type {
    switch (t.k) {
      case "number":
        return kt.type("Double");
      case "boolean":
        return kt.type("Boolean");
      case "string":
      case "enum":
        return kt.type("String");
      case "nullable":
        return kt.nullable(this.type(t.inner));
      case "array":
        return kt.type("List", this.type(t.element));
      case "object":
        return kt.type(this.dataClass(t));
    }
  }

  /** The value Compose state holds before the setup's effect sets it. */
  zero(t: ViewType): kt.Expr {
    switch (t.k) {
      case "number":
        return kt.num("0.0");
      case "boolean":
        return kt.bool(false);
      case "string":
      case "enum":
        return kt.str("");
      case "nullable":
        return kt.nullLit;
      case "array":
        return kt.call(kt.name("emptyList"), []);
      case "object":
        return kt.call(kt.name(this.dataClass(t)), []);
    }
  }

  /** The value of type `t` the boxed object `x` encodes. */
  decode(t: ViewType, x: kt.Expr): kt.Expr {
    switch (t.k) {
      case "number":
      case "boolean":
      case "string":
      case "enum":
        return kt.cast(x, this.type(t));
      case "nullable":
        return t.inner.k === "array" || t.inner.k === "object"
          ? kt.ifExpr(kt.binary(x, "==", kt.nullLit), kt.nullLit, this.decode(t.inner, x))
          : kt.cast(x, this.type(t));
      case "array":
        return kt.call(
          kt.member(kt.cast(x, kt.type("Array", kt.nullable(kt.type("Any")))), "map"),
          [],
          kt.lambda([], [kt.exprStmt(this.decode(t.element, kt.name("it")))]),
        );
      case "object":
        return kt.call(kt.name(`read${this.dataClass(t)}`), [{ value: x }]);
    }
  }

  /** The data class of an object type, named by its fields, and the function reading it. */
  private dataClass(t: ViewType & { k: "object" }): string {
    const key = JSON.stringify(t);
    const found = this.names.get(key);

    if (found) return found;

    const name = `${this.prefix}Value${this.names.size}`;
    const fields = kt.name("fields");

    this.names.set(key, name);
    this.decls.push(
      {
        k: "class",
        modifiers: ["data"],
        name,
        params: t.fields.map((f) => ({
          property: "val" as const,
          ...kt.param(f.name, this.type(fieldType(f)), this.zero(fieldType(f))),
        })),
        members: [],
      },
      {
        k: "fun",
        modifiers: ["private"],
        name: `read${name}`,
        params: [kt.param("x", kt.nullable(kt.type("Any")))],
        ret: kt.type(name),
        body: [
          kt.val("fields", kt.cast(kt.name("x"), kt.type("Array", kt.nullable(kt.type("Any"))))),
          kt.ret(
            kt.call(
              kt.name(name),
              t.fields.map((f, i) => ({
                value: this.decode(fieldType(f), kt.index(fields, kt.num(i))),
              })),
            ),
          ),
        ],
      },
    );

    return name;
  }
}

/** `fun <name>(slot: Int, value: Any?)`: assigns `slot`'s target, which the setup's C++ calls. */
function setter<S extends { readonly index: number }>(
  name: string,
  slots: readonly S[],
  assign: (slot: S, value: kt.Expr) => kt.Stmt,
): kt.Fun {
  return {
    k: "fun",
    modifiers: [],
    name,
    params: [kt.param("slot", kt.type("Int")), kt.param("value", kt.nullable(kt.type("Any")))],
    body: [
      {
        k: "when",
        subject: kt.name("slot"),
        branches: [
          ...slots.map((s) => ({
            conditions: [kt.num(s.index)],
            body: [assign(s, kt.name("value"))],
          })),
          {
            conditions: [],
            body: [
              kt.throwStmt(
                kt.call(kt.name("IllegalArgumentException"), [{ value: kt.str("no such slot") }]),
              ),
            ],
          },
        ],
      },
    ],
  };
}

/**
 * The state holder: Compose state per value slot and a function per
 * action slot, which the setup's C++ assigns (`set`, `setAction`).
 */
function stateClass(
  name: string,
  prefix: string,
  crossings: Crossings,
  values: KotlinValues,
): kt.Decl {
  const state = crossings.values.map((s): kt.Member => ({
    k: "val",
    modifiers: [],
    name: s.name,
    init: kt.call(kt.name("mutableStateOf"), [{ value: values.zero(s.type) }], undefined, [
      values.type(s.type),
    ]),
  }));
  const actions = crossings.actions.map((a): kt.Member => ({
    k: "var",
    modifiers: ["lateinit"],
    name: a.name,
    type: actionType(a),
  }));

  return {
    k: "class",
    name,
    members: [
      ...state,
      ...actions,
      ...crossings.lists.flatMap((l) => listMembers(values, l, `${prefix}Item${l.index}`)),
      setter("set", crossings.values, (s, value) =>
        kt.assign(kt.member(kt.name(s.name), "value"), values.decode(s.type, value)),
      ),
      setter("setAction", crossings.actions, (s, value) =>
        kt.assign(kt.name(s.name), kt.cast(value, actionType(s))),
      ),
      setter("setList", crossings.lists, (l, value) =>
        kt.assign(
          kt.member(kt.name(l.name), "value"),
          kt.call(kt.name(`merge${capital(l.name)}`), [{ value }]),
        ),
      ),
    ],
  };
}

const capital = (name: string) => `${name[0]!.toUpperCase()}${name.slice(1)}`;

/** A list's key in Kotlin: a String, or a Double. */
function keyType(list: ListSlot): ViewType {
  return { k: list.keyType.k };
}

/**
 * A list's item holder: its key, and Compose state per value the setup
 * computes for it, which a record sets in place (an equal value changes
 * nothing).
 */
function itemClass(values: KotlinValues, list: ListSlot, name: string): kt.Decl {
  const record = kt.name("record");

  return {
    k: "class",
    name,
    params: [{ property: "val", ...kt.param("key", values.type(keyType(list))) }],
    members: [
      ...list.values.map((v): kt.Member => ({
        k: "val",
        modifiers: [],
        name: v.name,
        init: kt.call(kt.name("mutableStateOf"), [{ value: values.zero(v.type) }], undefined, [
          values.type(v.type),
        ]),
      })),
      {
        k: "fun",
        modifiers: [],
        name: "update",
        params: [kt.param("record", kt.type("Array", kt.nullable(kt.type("Any"))))],
        body: list.values.map((v, i) =>
          kt.assign(
            kt.member(kt.name(v.name), "value"),
            values.decode(v.type, kt.index(record, kt.num(i + 1))),
          ),
        ),
      },
    ],
  };
}

/**
 * The holder's members for a list: its items (Compose state: the content
 * shows them), the items by key, and the merge of new records into them.
 * An item whose key stays keeps its holder; the list's state changes only
 * when the keys or their order do (lists of the same holders are equal).
 */
function listMembers(values: KotlinValues, list: ListSlot, item: string): kt.Member[] {
  const key = values.type(keyType(list));
  const byKey = `${list.name}Items`;
  const one = `${list.name}Item`;
  const records = kt.type("Array", kt.nullable(kt.type("Any")));

  return [
    {
      k: "val",
      modifiers: [],
      name: list.name,
      init: kt.call(
        kt.name("mutableStateOf"),
        [{ value: kt.call(kt.name("emptyList"), []) }],
        undefined,
        [kt.type("List", kt.type(item))],
      ),
    },
    {
      k: "val",
      modifiers: ["private"],
      name: byKey,
      init: kt.call(kt.name("HashMap"), [], undefined, [key, kt.type(item)]),
    },
    {
      k: "fun",
      modifiers: ["private"],
      name: `merge${capital(list.name)}`,
      params: [kt.param("records", kt.nullable(kt.type("Any")))],
      ret: kt.type("List", kt.type(item)),
      body: [
        kt.val(
          "next",
          kt.call(
            kt.member(kt.cast(kt.name("records"), records), "map"),
            [],
            kt.lambda(
              [],
              [kt.exprStmt(kt.call(kt.name(one), [{ value: kt.cast(kt.name("it"), records) }]))],
            ),
          ),
        ),
        kt.exprStmt(
          kt.call(kt.member(kt.member(kt.name(byKey), "keys"), "retainAll"), [
            {
              value: kt.call(
                kt.member(
                  kt.call(
                    kt.member(kt.name("next"), "map"),
                    [],
                    kt.lambda([], [kt.exprStmt(kt.member(kt.name("it"), "key"))]),
                  ),
                  "toSet",
                ),
                [],
              ),
            },
          ]),
        ),
        kt.ret(kt.name("next")),
      ],
    },
    {
      k: "fun",
      modifiers: ["private"],
      name: one,
      params: [kt.param("record", records)],
      ret: kt.type(item),
      body: [
        kt.val("key", values.decode(keyType(list), kt.index(kt.name("record"), kt.num(0)))),
        kt.val(
          "item",
          kt.call(
            kt.member(kt.name(byKey), "getOrPut"),
            [{ value: kt.name("key") }],
            kt.lambda([], [kt.exprStmt(kt.call(kt.name(item), [{ value: kt.name("key") }]))]),
          ),
        ),
        kt.exprStmt(kt.call(kt.member(kt.name("item"), "update"), [{ value: kt.name("record") }])),
        kt.ret(kt.name("item")),
      ],
    },
  ];
}

/**
 * The host object: gives the runtime's host of Compose content
 * (dev.lucent.compose.LucentComposition, which owns the ComposeView, its
 * composition and its disposal) the content, reading the state holder the
 * setup's C++ made. The composition reads each value where it uses it,
 * from the holder's state: nothing of the first commit is captured.
 */
function hostObject(names: { state: string; content: string; host: string }): kt.Decl {
  const content = kt.call(kt.name(names.content), [
    { value: kt.cast(kt.name("state"), kt.type(names.state)) },
  ]);

  const create: kt.Fun = {
    k: "fun",
    annotations: ["JvmStatic"],
    modifiers: [],
    name: "create",
    params: [kt.param("context", kt.type("Context")), kt.param("state", kt.type("Any"))],
    ret: kt.type(RUNTIME_HOST),
    body: [
      kt.ret(
        kt.call(
          kt.name(RUNTIME_HOST),
          [{ value: kt.name("context") }],
          kt.lambda([], [kt.exprStmt(content)]) as kt.Expr & { k: "lambda" },
        ),
      ),
    ],
  };

  return { k: "object", name: names.host, members: [create] };
}

