/**
 * The Kotlin of `setup`'s body: its composition statements, then the JSX
 * it returns, its slots found into `crossings`.
 */
export function composeContent(
  checker: ts.TypeChecker,
  setup: BodySetup,
  jsx: ts.Expression,
  lifted: readonly ts.Statement[],
  crossings: Crossings,
): ComposeContent {
  const r = setup.registration;
  const values = new KotlinValues(r);
  const helpers = new Map<FunctionLike, HelperFunction>();
  const writer = new BodyWriter(checker, jsx, lifted, crossings, { registration: r, helpers });
  const statements = writer.body();
  const names = { state: `${r}State`, content: `${r}Content`, host: `${r}Host` };
  // Made first: it meets every value type, whose data classes go before it.
  const state = stateClass(names.state, r, crossings, values);
  const items = crossings.lists.map((l) => itemClass(values, l, `${r}Item${l.index}`));

  const text = kt.printUnit({
    banner: `Generated by Lucent from ${setup.export}'s content. Do not edit.`,
    fileAnnotations: ['Suppress("UNCHECKED_CAST")'],
    packageName: PACKAGE,
    imports: [...new Set([...BASE_IMPORTS, ...writer.imports])].sort(),
    decls: [
      ...values.decls,
      ...items,
      state,
      {
        k: "fun",
        annotations: ["Composable"],
        modifiers: [],
        name: names.content,
        params: [kt.param(STATE, kt.type(names.state))],
        body: statements,
      },
      hostObject(names),
      ...[...helpers.values()].map((h) => helperFun(values, h)),
      ...(writer.usesText ? [TEXT_FUN] : []),
    ],
  });

  const jni = (name: string) => `${PACKAGE.replaceAll(".", "/")}/${name}`;

  return {
    stateClass: jni(names.state),
    hostClass: jni(names.host),
    file: `${PACKAGE.replaceAll(".", "/")}/${r}.kt`,
    kotlin: text,
  };
}

