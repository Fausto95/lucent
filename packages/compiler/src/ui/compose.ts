/**
 * A component's Compose content (Android): the JSX the component returns
 * and its composition statements (ui/composition.ts), compiled to Kotlin,
 * next to the slots through which the setup's C++ reaches it.
 *
 * The body is Compose written in TypeScript: a composable showing UI is a
 * JSX element, whose props are Kotlin's named arguments and whose
 * children are its trailing @Composable content lambda
 * (`<Box modifier={…}><BasicText text={…} /></Box>`), or a function of
 * the lambda's scope (`{(row) => …}`). Calls, modifier chains,
 * `remember`, effects and animations are Compose's own:
 * each declaration's binding (compose-api.ts) says what it is in Kotlin,
 * its parameters' names, kinds and number types. What the
 * body takes from its setup crosses through a generated state holder, one
 * slot each:
 *
 * - a prop (`props.on`), a signal (`taps.get()`) or a value a setup
 *   function computes, called where the body composes (`caption()`), is a
 *   value slot: Compose state, which an effect of the setup sets whenever
 *   what it reads changes, so the body recomposes;
 * - a setup function the body calls from a callback, or passes as one
 *   (`clickable(tap)`), is an action slot: a Kotlin function whose calls
 *   run the Lucent function in the main context.
 *
 * toolkit-body.ts finds the slots, as SwiftUI bodies' are found.
 *
 * The generated file (`dev/lucent/compose/<registration>.kt`) holds the
 * state class (`<registration>State`), the composable
 * (`<registration>Content`) and the host object (`<registration>Host`),
 * which gives the content to the runtime's host (LucentComposition, in
 * the same package). Anything the body does that has no Kotlin form here
 * fails with a diagnostic.
 */
