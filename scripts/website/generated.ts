import { Explanations, formatDiagnostic } from "../../packages/compiler/src/index.ts";
import { GLOBAL_FLAGS } from "../../packages/lucent/src/cli/args.ts";
import { commands } from "../../packages/lucent/src/cli/commands.ts";
import { docsEntries } from "../../apps/website/src/docs/nav.ts";
import { docsRedirects } from "../../apps/website/src/docs/redirects.ts";
import { docsHref } from "../../apps/website/src/docs/types.ts";
import { compileSamples } from "./compile.ts";

const header = "// Generated by scripts/website.ts. Do not edit.\n\n";
const json = (value: unknown): string => JSON.stringify(value, null, 2);

/** The homepage's sample and the C++ the compiler writes for it. */
function compilerDemo(): string {
  const source = `export type Point = { x: number; y: number };

export function squaredDistance(a: Point, b: Point): number {
  const dx = a.x - b.x;
  const dy = a.y - b.y;
  return dx * dx + dy * dy;
}
`;
  const demo = compileSamples("home", [{ filename: "geo.lucent.ts", code: source }]);
  const cpp = demo.files.get("m_geo.cpp");
  if (!cpp) throw new Error(`the homepage sample does not compile:\n${demo.diagnostics.map(formatDiagnostic).join("\n")}`);
  // The function as the compiler wrote it, minus the #line directives that map it back to the source.
  const fn = cpp
    .slice(cpp.indexOf("double m_geo::squaredDistance"), cpp.indexOf("\n}\n") + 2)
    .split("\n")
    .filter((line) => !line.startsWith("#line"))
    .join("\n");
  return `${header}export const demoSource = ${JSON.stringify(source.trimEnd())};\n\nexport const demoCpp = ${JSON.stringify(fn)};\n`;
}

/** The CLI reference, from the command table the CLI parses with. */
function cli(): string {
  const flag = (f: { name: string; value?: string; optional?: boolean }) => `--${f.name}${f.value ? (f.optional ? ` [<${f.value}>]` : ` <${f.value}>`) : ""}`;
  return `${header}export const cliCommands: { name: string; summary: string; flags: { flag: string; description: string }[] }[] = ${json(
    commands.map((c) => ({ name: c.name, summary: c.summary, flags: c.flags.map((f) => ({ flag: flag(f), description: f.description })) })),
  )};\n\nexport const globalFlags: { flag: string; description: string }[] = ${json(
    GLOBAL_FLAGS.map((f) => ({ flag: flag(f), description: f.description })),
  )};\n`;
}

/** The same explanations as `lucent explain`; their examples are checked by the compiler's tests. */
function diagnostics(): string {
  return `${header}export const explanations: { code: string; title: string; summary: string; details: string; fix: string; wrong: Record<string, string>; right: Record<string, string> }[] = ${json(
    Object.entries(Explanations).map(([code, { title, summary, details, fix, wrong, right }]) => ({ code, title, summary, details, fix, wrong, right })),
  )};\n`;
}

/**
 * One TanStack Router route per docs page and per retired slug, written out
 * so every path is a literal type: links to docs pages type-check.
 */
function docsRoutes(): string {
  const pages = docsEntries.map(
    (e) => `  createRoute({ getParentRoute: () => docsRoute, path: ${JSON.stringify(e.slug || "/")}, ...docPage(${JSON.stringify(e.slug)}) }),`,
  );
  const redirects = Object.entries(docsRedirects).map(
    ([from, to]) => `  createRoute({
    getParentRoute: () => docsRoute,
    path: ${JSON.stringify(from)},
    beforeLoad: ({ location }) => {
      throw redirect({ to: ${JSON.stringify(docsHref(to))}, ...keepHash(location), replace: true });
    },
  }),`,
  );
  return `// Generated by scripts/website.ts from src/docs/nav.ts and src/docs/redirects.ts. Do not edit.

import { createRoute, redirect } from "@tanstack/react-router";
import { docPage, docsRoute, keepHash } from "../routes/docs";

export const docsPageRoutes = [
${pages.join("\n")}
] as const;

export const docsRedirectRoutes = [
${redirects.join("\n")}
] as const;
`;
}

/** apps/website/src/generated/<name> → its content. */
export function generatedFiles(): Record<string, string> {
  return { "compiler-demo.ts": compilerDemo(), "cli.ts": cli(), "diagnostics.ts": diagnostics(), "docs-routes.ts": docsRoutes() };
}
