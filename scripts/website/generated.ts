/** A repository file as a page shows it: a module without its opening comment, which the page replaces. */
function snippet(file: string): string {
  const lines = fs.readFileSync(path.join(root, file), "utf8").split("\n");
  const start = /\.tsx?$/.test(file) ? lines.findIndex((line) => !line.startsWith("//")) : 0;
  return `${lines.slice(start).join("\n").trimEnd()}\n`;
}

const schemasDir = path.join(root, "packages/lucent/schemas");
const schemaOf = (file: string): SchemaNode =>
  JSON.parse(fs.readFileSync(path.join(schemasDir, file), "utf8")) as SchemaNode;

/** The lucent.json reference: every field of its schema, nested ones by path. */
function lucentJson(): string {
  const schema = schemaOf("lucent.schema.json");
  return `${header}/** From packages/lucent/schemas/lucent.schema.json. */\nexport const lucentJsonDescription = ${JSON.stringify(schema.description ?? "")};\n\nexport const lucentJsonFields: { field: string; type: string; required: boolean; description: string }[] = ${json(schemaFields(schema))};\n`;
}

/** Each command's --json output and the SDK lock file, from their schemas. */
function jsonFormats(): string {
  const files = fs
    .readdirSync(schemasDir)
    .filter((f) => f.endsWith(".schema.json"))
    .sort();
  const outputs = jsonOutputs(
    files.map((file) => ({ file, schema: schemaOf(file) })),
    commands,
  );
  const lock = schemaOf("sdk-lock.schema.json");
  const field = "{ field: string; type: string; required: boolean; description: string }";
  return `${header}/** From packages/lucent/schemas/*.schema.json. */\nexport const jsonOutputs: { command: string; file: string; description: string; variants: { description: string; fields: ${field}[] }[] }[] = ${json(outputs)};\n\nexport const sdkLock: { description: string; fields: ${field}[] } = ${json({ description: lock.description ?? "", fields: schemaFields(lock) })};\n`;
}

/** Each lucent:* module and the globals, read per export from the declarations the compiler serves. */
function apiModules(): string {
  const lib = path.join(root, "packages/compiler/lib");
  const files: Record<string, string> = {
    core: "sdk/core.d.ts",
    platform: "sdk/platform.d.ts",
    thread: "sdk/thread.d.ts",
    ios: "sdk/ios.d.ts",
    android: "sdk/android.d.ts",
    globals: "globals.d.ts",
    ui: "sdk/ui.d.ts",
    compose: "sdk/compose.d.ts",
  };
  const modules = Object.fromEntries(
    Object.entries(files).map(([name, file]) => [
      name,
      declarationsOf(file, fs.readFileSync(path.join(lib, file), "utf8")),
    ]),
  );
  return `${header}import type { ModuleDeclarations } from "../docs/api";\n\n/** From packages/compiler/lib/sdk/*.d.ts and lib/globals.d.ts. */\nexport const apiModules: Record<string, ModuleDeclarations> = ${json(modules)};\n`;
}

/** What Lucent needs, as lucent doctor and the compiler check it. */
