/**
 * Copies the end-to-end cases into both example apps, so the on-device test
 * screen runs exactly what CI runs through Hermes. Expected output comes from
 * running each case's TypeScript source as plain JavaScript.
 *
 *   tsx scripts/sync-examples.ts
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { cases, referenceRun } from "../packages/compiler/test/e2e/run.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const apps = ["apps/bare-example", "apps/expo-example"];

const all = cases([]).filter((c) => c.files.length === 1);
const expected: Record<string, string[]> = {};
for (const c of all) {
  const out = await referenceRun(c);
  expected[c.name] = out.split("\n").filter((l, i, a) => i < a.length - 1 || l !== "");
}

for (const app of apps) {
  const lucentDir = path.join(root, app, "src/lucent");
  const testsDir = path.join(root, app, "src/tests");
  fs.rmSync(lucentDir, { recursive: true, force: true });
  fs.rmSync(testsDir, { recursive: true, force: true });
  fs.mkdirSync(lucentDir, { recursive: true });
  fs.mkdirSync(testsDir, { recursive: true });
  const index: string[] = [
    "// Generated by scripts/sync-examples.ts. Do not edit.",
    "/* eslint-disable */",
    "import type { TestCase } from \"./types\";",
  ];
  const entries: string[] = [];
  for (const c of all) {
    fs.copyFileSync(c.files[0]!, path.join(lucentDir, path.basename(c.files[0]!)));
    const body = fs.readFileSync(c.test, "utf8");
    fs.writeFileSync(
      path.join(testsDir, `${c.name}.ts`),
      `// Generated from packages/compiler/test/e2e/cases/${c.name}.test.js. Do not edit.\n` +
        `// @ts-nocheck\n` +
        `export default function run(mod, print, lucentClass, mods) {\n${body
          .split("\n")
          .map((l) => (l ? `  ${l}` : l))
          .join("\n")}\n}\n`,
    );
    index.push(`import * as ${c.name}Module from "../lucent/${c.name}.lucent";`);
    index.push(`import ${c.name}Run from "./${c.name}";`);
    entries.push(`  { name: ${JSON.stringify(c.name)}, module: ${c.name}Module, run: ${c.name}Run, expected: ${JSON.stringify(expected[c.name])} },`);
  }
  index.push("", "export const cases: TestCase[] = [", ...entries, "];", "");
  fs.writeFileSync(path.join(testsDir, "index.ts"), index.join("\n"));
  fs.writeFileSync(
    path.join(testsDir, "types.ts"),
    `// Generated by scripts/sync-examples.ts. Do not edit.
export interface TestCase {
  name: string;
  module: unknown;
  run: (mod: unknown, print: (...args: unknown[]) => void, lucentClass: (x: unknown) => unknown, mods: unknown) => void;
  expected: string[];
}
`,
  );
  console.log(`✓ ${app}: ${all.length} cases`);
}
