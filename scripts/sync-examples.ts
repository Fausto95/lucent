/**
 * Generates both example apps' JavaScript side (App.tsx and src/) from one
 * source, so they stay the same app:
 *
 *   - scripts/example-app: the shared app (Examples, Lab, the design system);
 *     an app's overlay directory (scripts/example-app-bare) replaces or adds
 *     files for that app only;
 *   - the end-to-end cases (packages/compiler/test/e2e/cases), which the
 *     Lab's Tests screen runs natively against the lines the same code
 *     prints as plain JavaScript;
 *   - the Lab's benchmark (the kernels case again, as plain TypeScript, and
 *     kernels.bench.json's sizes) and its comparison with other native
 *     module kinds (NitroBenchmarks), over the benchmarks/* packages the app
 *     depends on;
 *   - the image filter demo's module again as plain TypeScript, which the
 *     demo times as JavaScript.
 *
 * App.tsx and src/ are rewritten whole: a file removed from the source
 * leaves no copy behind. Unit tests (*.test.ts) stay out.
 *
 *   node scripts/sync-examples.ts
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { LUCENT_EXTENSION, moduleNameOf } from "../packages/compiler/src/index.ts";
import { cases, referenceRun } from "../packages/compiler/test/e2e/run.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const shared = "scripts/example-app";

const apps = [
  { dir: "apps/bare-example", overlay: "scripts/example-app-bare" },
  { dir: "apps/expo-example" },
];

const e2e = "packages/compiler/test/e2e/cases";

/** Where the generated parts go, under an app's src/. */
const out = {
  caseModules: "lab/tests/lucent",
  caseRunners: "lab/tests/cases",
  bench: "lab/bench",
  compare: "lab/compare/modules.ts",
  pixels: "demos/compute",
};

/** NitroBenchmarks' modules, in its order, by the workspace package that builds each. */
const compared = [
  { name: "ExpoModule", pkg: "bench-expo", binding: "BenchExpo" },
  { name: "TurboModule", pkg: "bench-turbo", binding: "BenchTurbo" },
  { name: "NitroModule", pkg: "bench-nitro", binding: "BenchNitro" },
  { name: "CxxNitroModule", pkg: "bench-nitro", binding: "BenchNitroCxx" },
  { name: "CxxTurboModule", pkg: "bench-turbo-cxx", binding: "BenchTurboCxx" },
];

/** A JavaScript identifier for a case name, which may hold hyphens: assignment-order → assignmentOrder. */
function identifier(name: string): string {
  const camel = name.replace(/[^A-Za-z0-9_$]+(.?)/g, (_, c: string) => c.toUpperCase());
  return /^[0-9]/.test(camel) ? `case${camel}` : camel;
}

const banner = (from: string) =>
  `// Generated by scripts/sync-examples.ts from ${from}. Do not edit.\n`;

function write(file: string, text: string): void {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
}

// Cases with native extensions need their packages installed in the app: they run in the e2e host only.
const single = cases([]).filter((c) => c.files.length === 1 && !c.packages);

for (const app of apps) refuseClashes(app);

const expected: Record<string, string[]> = {};
for (const c of single) {
  const printed = await referenceRun(c, { logs: false });
  expected[c.name] = printed.split("\n").filter((l, i, a) => i < a.length - 1 || l !== "");
}

for (const app of apps) {
  const appDir = path.join(root, app.dir);
  const src = path.join(appDir, "src");

  fs.rmSync(src, { recursive: true, force: true });
  fs.rmSync(path.join(appDir, "App.tsx"), { force: true });

  installTree(shared, appDir);
  if (app.overlay) installTree(app.overlay, appDir);

  installCases(src);
  installBench(src);
  installCompare(appDir, src);
  installPixels(src);

  console.log(`✓ ${app.dir}: ${single.length} cases`);
}

/**
 * Fails before anything is written when a case would share its module name
 * with one of the app's own Lucent modules: the app would not compile.
 */
function refuseClashes(app: (typeof apps)[number]): void {
  const owned = new Map<string, string>();

  const walk = (dir: string): void => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const file = path.join(dir, entry.name);

      if (entry.isDirectory()) walk(file);
      else if (LUCENT_EXTENSION.test(entry.name)) owned.set(moduleNameOf(entry.name), file);
    }
  };

  walk(path.join(root, shared));
  if (app.overlay) walk(path.join(root, app.overlay));

  for (const c of single) {
    const name = moduleNameOf(path.basename(c.files[0]!));
    const clash = owned.get(name);

    if (clash) {
      throw new Error(
        `${app.dir}: the e2e case "${c.name}" and ${path.relative(root, clash)} are both Lucent modules named "${name}"; rename the case`,
      );
    }
  }
}

/** Copies a source tree into the app, with a banner on each TypeScript file. */
function installTree(from: string, appDir: string): void {
  const walk = (rel: string): void => {
    const source = path.join(root, from, rel);

    if (fs.statSync(source).isDirectory()) {
      for (const entry of fs.readdirSync(source)) walk(path.join(rel, entry));
      return;
    }

    if (rel.endsWith(".test.ts")) return;

    const text = fs.readFileSync(source, "utf8");
    const origin = path.posix.join(from, rel.split(path.sep).join("/"));

    write(path.join(appDir, rel), /\.tsx?$/.test(rel) ? banner(origin) + text : text);
  };

  walk(".");
}

/**
 * The e2e cases: each module as is (it compiles to the same C++ as in the
 * suite), and its test as a function the Tests screen calls.
 */
function installCases(src: string): void {
  const modules = path.join(src, out.caseModules);
  const runners = path.join(src, out.caseRunners);

  const index = [
    banner(e2e).trimEnd(),
    "/* eslint-disable */",
    'import type { TestCase } from "./types";',
  ];
  const entries: string[] = [];

  for (const c of single) {
    const file = c.files[0]!;
    write(path.join(modules, path.basename(file)), fs.readFileSync(file, "utf8"));

    const body = fs
      .readFileSync(c.test, "utf8")
      .split("\n")
      .map((l) => (l ? `  ${l}` : l))
      .join("\n");
    write(
      path.join(runners, `${c.name}.ts`),
      banner(`${e2e}/${c.name}.test.js`) +
        "// @ts-nocheck\n" +
        `export default function run(mod, print, lucentClass, mods) {\n${body}\n}\n`,
    );

    const module = path.posix.relative(out.caseRunners, `${out.caseModules}/${c.name}.lucent`);
    const id = identifier(c.name);
    index.push(`import * as ${id}Module from "${module}";`);
    index.push(`import ${id}Run from "./${c.name}";`);
    entries.push(
      `  { name: ${JSON.stringify(c.name)}, module: ${id}Module, run: ${id}Run, expected: ${JSON.stringify(expected[c.name])} },`,
    );
  }

  index.push("", "export const cases: TestCase[] = [", ...entries, "];", "");
  write(path.join(runners, "index.ts"), index.join("\n"));

  write(
    path.join(runners, "types.ts"),
    `${banner(e2e)}export interface TestCase {
  name: string;
  module: unknown;
  run: (mod: unknown, print: (...args: unknown[]) => void, lucentClass: (x: unknown) => unknown, mods: unknown) => void;
  expected: string[];
}
`,
  );
}

/** The kernels case as plain TypeScript, bundled as JavaScript, and the sizes to run it at. */
function installBench(src: string): void {
  const dir = path.join(src, out.bench);

  write(
    path.join(dir, "kernels.ts"),
    banner(`${e2e}/kernels.lucent.ts`) +
      `// The same source as src/${out.caseModules}/kernels.lucent.ts, bundled as JavaScript.\n` +
      fs.readFileSync(path.join(root, e2e, "kernels.lucent.ts"), "utf8"),
  );

  const sizes = fs.readFileSync(path.join(root, e2e, "kernels.bench.json"), "utf8").trim();
  write(
    path.join(dir, "sizes.ts"),
    `${banner(`${e2e}/kernels.bench.json`)}export const sizes = ${sizes};\n`,
  );
}

/** The Compare screen's modules: those the app depends on, then Lucent. */
function installCompare(appDir: string, src: string): void {
  const pkg = JSON.parse(fs.readFileSync(path.join(appDir, "package.json"), "utf8")) as {
    dependencies?: Record<string, string>;
  };
  const present = compared.filter((m) => pkg.dependencies?.[m.pkg]);

  // Loaded on first use, so a module the native build lacks fails its own
  // row instead of the screen.
  const lines = [
    banner("the app's benchmarks/* dependencies").trimEnd(),
    'import * as Lucent from "./compare.lucent";',
    'import type { CompareModule } from "./types";',
    "",
    "export const modules: CompareModule[] = [",
    ...present.map((m) => `  { name: "${m.name}", load: () => require("${m.pkg}").${m.binding} },`),
    '  { name: "Lucent", load: () => Lucent },',
    "];",
    "",
  ];
  write(path.join(src, out.compare), lines.join("\n"));
}

/** The image filter demo's module as plain TypeScript: what the demo times as JavaScript. */
function installPixels(src: string): void {
  const from = `${shared}/src/${out.pixels}/pixels.lucent.ts`;

  write(
    path.join(src, out.pixels, "pixels.ts"),
    banner(from) +
      "// The same source as pixels.lucent.ts, bundled as JavaScript.\n" +
      fs.readFileSync(path.join(root, from), "utf8"),
  );
}
