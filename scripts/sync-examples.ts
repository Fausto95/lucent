/**
 * Copies the end-to-end cases into both example apps, so the on-device test
 * screen runs exactly what CI runs through Hermes. Expected output comes from
 * running each case's TypeScript source as plain JavaScript.
 *
 * Also installs the shared app UI (scripts/example-app) and the benchmark:
 * the kernels case as plain TypeScript (bundled as JavaScript) next to its
 * Lucent copy, with the sizes from kernels.bench.json.
 *
 *   tsx scripts/sync-examples.ts
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { cases, referenceRun } from "../packages/compiler/test/e2e/run.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const apps = ["apps/bare-example", "apps/expo-example"];

const all = cases([]).filter((c) => c.files.length === 1);
const expected: Record<string, string[]> = {};
for (const c of all) {
  const out = await referenceRun(c);
  expected[c.name] = out.split("\n").filter((l, i, a) => i < a.length - 1 || l !== "");
}

for (const app of apps) {
  const lucentDir = path.join(root, app, "src/lucent");
  const testsDir = path.join(root, app, "src/tests");
  fs.rmSync(lucentDir, { recursive: true, force: true });
  fs.rmSync(testsDir, { recursive: true, force: true });
  fs.mkdirSync(lucentDir, { recursive: true });
  fs.mkdirSync(testsDir, { recursive: true });
  const index: string[] = [
    "// Generated by scripts/sync-examples.ts. Do not edit.",
    "/* eslint-disable */",
    "import type { TestCase } from \"./types\";",
  ];
  const entries: string[] = [];
  for (const c of all) {
    fs.copyFileSync(c.files[0]!, path.join(lucentDir, path.basename(c.files[0]!)));
    const body = fs.readFileSync(c.test, "utf8");
    fs.writeFileSync(
      path.join(testsDir, `${c.name}.ts`),
      `// Generated from packages/compiler/test/e2e/cases/${c.name}.test.js. Do not edit.\n` +
        `// @ts-nocheck\n` +
        `export default function run(mod, print, lucentClass, mods) {\n${body
          .split("\n")
          .map((l) => (l ? `  ${l}` : l))
          .join("\n")}\n}\n`,
    );
    index.push(`import * as ${c.name}Module from "../lucent/${c.name}.lucent";`);
    index.push(`import ${c.name}Run from "./${c.name}";`);
    entries.push(`  { name: ${JSON.stringify(c.name)}, module: ${c.name}Module, run: ${c.name}Run, expected: ${JSON.stringify(expected[c.name])} },`);
  }
  index.push("", "export const cases: TestCase[] = [", ...entries, "];", "");
  fs.writeFileSync(path.join(testsDir, "index.ts"), index.join("\n"));
  fs.writeFileSync(
    path.join(testsDir, "types.ts"),
    `// Generated by scripts/sync-examples.ts. Do not edit.
export interface TestCase {
  name: string;
  module: unknown;
  run: (mod: unknown, print: (...args: unknown[]) => void, lucentClass: (x: unknown) => unknown, mods: unknown) => void;
  expected: string[];
}
`,
  );
  installUi(path.join(root, app));
  installBench(path.join(root, app));
  installParity(path.join(root, app));
  console.log(`✓ ${app}: ${all.length} cases`);
}

function installUi(appDir: string): void {
  const ui = path.join(root, "scripts/example-app");
  // Generated wholesale: a module that changes layout (split into platform files, or merged) leaves no files behind.
  for (const dir of ["src/screens", "src/sdk"]) fs.rmSync(path.join(appDir, dir), { recursive: true, force: true });
  const copy = (rel: string) => {
    const from = path.join(ui, rel);
    if (fs.statSync(from).isDirectory()) return fs.readdirSync(from).forEach((f) => copy(path.join(rel, f)));
    fs.mkdirSync(path.dirname(path.join(appDir, rel)), { recursive: true });
    fs.copyFileSync(from, path.join(appDir, rel));
  };
  copy(".");
}

function installBench(appDir: string): void {
  const cases = path.join(root, "packages/compiler/test/e2e/cases");
  const dir = path.join(appDir, "src/bench");
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(
    path.join(dir, "kernels.ts"),
    "// Generated by scripts/sync-examples.ts from packages/compiler/test/e2e/cases/kernels.lucent.ts.\n" +
      "// The same source as src/lucent/kernels.lucent.ts, bundled as JavaScript. Do not edit.\n" +
      fs.readFileSync(path.join(cases, "kernels.lucent.ts"), "utf8"),
  );
  const sizes = fs.readFileSync(path.join(cases, "kernels.bench.json"), "utf8").trim();
  fs.writeFileSync(path.join(dir, "sizes.ts"), `// Generated by scripts/sync-examples.ts from kernels.bench.json. Do not edit.\nexport const sizes = ${sizes};\n`);
}

/**
 * The SDK screen's parity cases: where the app has expo-haptics, the original
 * package runs next to the Lucent port, through the same JavaScript API.
 */
function installParity(appDir: string): void {
  const pkg = JSON.parse(fs.readFileSync(path.join(appDir, "package.json"), "utf8")) as { dependencies?: Record<string, string> };
  const header = "// Generated by scripts/sync-examples.ts. Do not edit.\n";
  const body = pkg.dependencies?.["expo-haptics"]
    ? `import AsyncStorage from "@react-native-async-storage/async-storage";
import * as ExpoApplication from "expo-application";
import * as ExpoClipboard from "expo-clipboard";
import * as ExpoDevice from "expo-device";
import * as Haptics from "expo-haptics";
import * as ExpoLocalAuthentication from "expo-local-authentication";
import * as ExpoLocation from "expo-location";
import * as ExpoSecureStore from "expo-secure-store";
import * as Application from "./application.lucent";
import * as Clipboard from "./clipboard.lucent";
import * as Device from "./device.lucent";
import { ImpactFeedbackStyle, NotificationFeedbackType } from "lucent-haptics";
import * as LocalAuthentication from "./localAuthentication.lucent";
import * as Location from "./location.lucent";
import * as SecureStore from "lucent-secure-store";
import * as Storage from "./storage.lucent";
import type { SdkCase } from "./types";

const done = (p: Promise<void>) => p.then(() => "ok");
const values = (e: object) => JSON.stringify(Object.values(e));

/** The same steps against the original package and the Lucent port. */
async function storageSteps(s: { clear(): Promise<void>; setItem(k: string, v: string): Promise<void>; multiSet(p: [string, string][]): Promise<void>; removeItem(k: string): Promise<void>; getAllKeys(): Promise<readonly string[]>; multiGet(k: string[]): Promise<readonly (readonly [string, string | null])[]>; getItem(k: string): Promise<string | null> }): Promise<string> {
  await s.clear();
  await s.setItem("a", "1");
  await s.multiSet([["b", "2"], ["c", "3"]]);
  await s.removeItem("c");
  const keys = [...(await s.getAllKeys())].sort();
  return \`\${JSON.stringify(keys)} \${JSON.stringify(await s.multiGet(["a", "b", "c"]))} \${await s.getItem("b")}\`;
}

/** What a device's biometrics look like through either implementation. */
async function authSteps(m: { hasHardwareAsync(): Promise<boolean>; isEnrolledAsync(): Promise<boolean>; supportedAuthenticationTypesAsync(): Promise<number[]>; getEnrolledLevelAsync(): Promise<number> }): Promise<string> {
  return JSON.stringify([await m.hasHardwareAsync(), await m.isEnrolledAsync(), await m.supportedAuthenticationTypesAsync(), await m.getEnrolledLevelAsync()]);
}

/** A position to three decimals (about 100 m), for comparing two providers' fixes. */
const near = (l: { coords: { latitude: number; longitude: number } } | null) => (l ? \`\${l.coords.latitude.toFixed(3)},\${l.coords.longitude.toFixed(3)}\` : "none");

export const parityCases: SdkCase[] = [
  {
    name: "same as expo-location: permission, services, provider",
    run: async () => {
      const steps = async (m: { getForegroundPermissionsAsync(): Promise<{ status: string; granted: boolean }>; hasServicesEnabledAsync(): Promise<boolean>; getProviderStatusAsync(): Promise<{ locationServicesEnabled: boolean }> }) => {
        const p = await m.getForegroundPermissionsAsync();
        return JSON.stringify([p.status, p.granted, await m.hasServicesEnabledAsync(), (await m.getProviderStatusAsync()).locationServicesEnabled]);
      };
      const [a, b] = [await steps(Location), await steps(ExpoLocation)];
      return a === b ? "same" : \`lucent \${a} expo \${b}\`;
    },
    expected: "same",
  },
  {
    name: "same current position as expo-location",
    run: async () => {
      // High accuracy (GPS), as the port asks: simulators' and emulators' fixes come through it.
      const [a, b] = [near(await Location.getCurrentPositionAsync()), near(await ExpoLocation.getCurrentPositionAsync({ accuracy: ExpoLocation.Accuracy.High }))];
      return a === b ? \`same \${a}\` : \`lucent \${a} expo \${b}\`;
    },
    expected: /^same /,
  },
  {
    name: "same as expo-local-authentication",
    run: async () => {
      const [a, b] = [await authSteps(LocalAuthentication), await authSteps(ExpoLocalAuthentication)];
      return a === b ? "same" : \`lucent \${a} expo \${b}\`;
    },
    expected: "same",
  },
  {
    name: "authenticateAsync like expo-local-authentication",
    run: async () => {
      // Biometrics only, so no passcode prompt waits for a person.
      const options = { promptMessage: "Lucent parity", disableDeviceFallback: true };
      const shape = (r: { success: boolean; error?: string }) => JSON.stringify([r.success, r.success ? null : r.error]);
      const [a, b] = [shape(await LocalAuthentication.authenticateAsync(options)), shape(await ExpoLocalAuthentication.authenticateAsync(options))];
      return a === b ? \`same \${a}\` : \`lucent \${a} expo \${b}\`;
    },
    expected: /^same /,
  },
  {
    name: "same as expo-application",
    run: async () =>
      JSON.stringify([Application.applicationId(), Application.applicationName(), Application.nativeApplicationVersion(), Application.nativeBuildVersion()]) ===
      JSON.stringify([ExpoApplication.applicationId, ExpoApplication.applicationName, ExpoApplication.nativeApplicationVersion, ExpoApplication.nativeBuildVersion])
        ? "same"
        : \`lucent \${JSON.stringify([Application.applicationId(), Application.applicationName(), Application.nativeApplicationVersion(), Application.nativeBuildVersion()])} expo \${JSON.stringify([ExpoApplication.applicationId, ExpoApplication.applicationName, ExpoApplication.nativeApplicationVersion, ExpoApplication.nativeBuildVersion])}\`,
    expected: "same",
  },
  {
    name: "same installation time as expo-application",
    run: async () => {
      const [a, b] = [(await Application.getInstallationTimeAsync()).getTime(), (await ExpoApplication.getInstallationTimeAsync()).getTime()];
      return a === b ? "same" : \`lucent \${a} expo \${b}\`;
    },
    expected: "same",
  },
  {
    name: "same as expo-device",
    run: async () => {
      const d = await Device.getDeviceInfoAsync();
      const lucent = JSON.stringify([d.brand, d.manufacturer, d.osName, d.osVersion, d.totalMemory]);
      const expo = JSON.stringify([ExpoDevice.brand, ExpoDevice.manufacturer, ExpoDevice.osName, ExpoDevice.osVersion, ExpoDevice.totalMemory]);
      return lucent === expo ? "same" : \`lucent \${lucent} expo \${expo}\`;
    },
    expected: "same",
  },
  {
    name: "clipboard shared with expo-clipboard",
    run: async () => {
      await Clipboard.setStringAsync("from lucent");
      const a = await ExpoClipboard.getStringAsync();
      await ExpoClipboard.setStringAsync("from expo");
      return \`\${a} | \${await Clipboard.getStringAsync()} \${await Clipboard.hasStringAsync() === (await ExpoClipboard.hasStringAsync())}\`;
    },
    expected: "from lucent | from expo true",
  },
  {
    name: "async-storage steps give the same results",
    run: async () => {
      const [a, b] = [await storageSteps(Storage), await storageSteps(AsyncStorage)];
      return a === b ? "same" : \`lucent \${a} original \${b}\`;
    },
    expected: "same",
  },
  {
    name: "secure-store steps give the same results",
    run: async () => {
      const steps = async (s: { setItemAsync(k: string, v: string): Promise<void>; getItemAsync(k: string): Promise<string | null>; deleteItemAsync(k: string): Promise<void> }) => {
        await s.setItemAsync("parity", "one");
        await s.setItemAsync("parity", "two");
        const v = await s.getItemAsync("parity");
        await s.deleteItemAsync("parity");
        return \`\${v} \${await s.getItemAsync("parity")}\`;
      };
      const [a, b] = [await steps(SecureStore), await steps(ExpoSecureStore)];
      return a === b ? "same" : \`lucent \${a} expo \${b}\`;
    },
    expected: "same",
  },
  { name: "expo-haptics.impactAsync(Heavy)", run: () => done(Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Heavy)), expected: "ok" },
  { name: "expo-haptics.notificationAsync(Error)", run: () => done(Haptics.notificationAsync(Haptics.NotificationFeedbackType.Error)), expected: "ok" },
  { name: "expo-haptics.selectionAsync()", run: () => done(Haptics.selectionAsync()), expected: "ok" },
  { name: "same enums as expo-haptics", run: async () => \`\${values(ImpactFeedbackStyle) === values(Haptics.ImpactFeedbackStyle)} \${values(NotificationFeedbackType) === values(Haptics.NotificationFeedbackType)}\`, expected: "true true" },
];
`
    : `import { Platform } from "react-native";
import { linkedLibraries } from "./linked.lucent";
import type { SdkCase } from "./types";

// Lucent binds what the app already links like the SDK: React Native's pods
// on iOS, AndroidX on Android (scripts/example-app-bare).
export const parityCases: SdkCase[] = [
  {
    name: "linked libraries (React Native's pods; AndroidX)",
    run: linkedLibraries,
    expected: Platform.OS === "ios" ? /^\\d+ request handlers, \\d+ image decoders$/ : "INTERNET granted true",
  },
];
`;
  if (!pkg.dependencies?.["expo-haptics"]) {
    const extra = path.join(root, "scripts/example-app-bare/src/sdk");
    for (const f of fs.readdirSync(extra)) fs.copyFileSync(path.join(extra, f), path.join(appDir, "src/sdk", f));
  }
  fs.writeFileSync(path.join(appDir, "src/sdk/parity.ts"), header + body);
}
