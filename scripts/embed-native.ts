/**
 * Embeds `packages/compiler/native/*` into a generated TypeScript module.
 *
 * Every other package reads its native assets from disk, but the compiler is
 * pure by contract — it imports nothing but `oxc-parser` (see AGENTS.md), so it
 * cannot touch `node:fs`. Generating the embed keeps the hand-written Swift and
 * Kotlin in real files that editors, formatters and the toolchains can read,
 * while the compiler still ships a self-contained module.
 *
 * `--check` fails when the embed is stale instead of rewriting it; `pnpm verify`
 * runs it that way so a native edit cannot land without its regenerated module.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const nativeDir = join(root, "packages/compiler/native");
const target = join(root, "packages/compiler/src/libraries/native-sources.generated.ts");

const files = readdirSync(nativeDir)
  .filter((f) => f.endsWith(".swift") || f.endsWith(".kt"))
  .toSorted();

const entries = files.map((file) => {
  const source = readFileSync(join(nativeDir, file), "utf8");
  return `  ${JSON.stringify(file)}: ${JSON.stringify(source)},`;
});

const generated = `// Generated by scripts/embed-native.ts from packages/compiler/native. Do not edit.

/** Hand-written Swift and Kotlin shipped with the built-in libraries. */
export const NATIVE_SOURCES: Readonly<Record<string, string>> = {
${entries.join("\n")}
};

export const nativeSource = (file: string): string => {
  const source = NATIVE_SOURCES[file];
  if (source === undefined) throw new Error(\`Unknown native source \${file}\`);
  return source;
};
`;

function readIfPresent(path: string): string | null {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

if (process.argv.includes("--check")) {
  if (readIfPresent(target) !== generated) {
    console.error(
      `${target} is stale.\nRun \`npx tsx scripts/embed-native.ts\` and commit the result alongside the native change.`,
    );
    process.exit(1);
  }
  console.log(`✓ native embed matches ${files.length} files`);
} else {
  writeFileSync(target, generated);
  console.log(`✓ embedded ${files.length} native files`);
}
